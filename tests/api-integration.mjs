// Run against the local Wrangler emulator: node tests/api-integration.mjs
import assert from 'node:assert/strict';
import { emptyDocument, mergeDocuments, recordAnswer, summarize } from '../progress-model.js';
const base = process.argv[2] || 'http://127.0.0.1:8787';
if (!/^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(base)) throw new Error('Integration tests require a local disposable database.');
const name = `integration-${Date.now()}`, path = `${base}/api/progress/${name}`;
const a = 'aaaaaaaa-aaaa-4aaa-aaaa-aaaaaaaaaaaa', b = 'bbbbbbbb-bbbb-4bbb-bbbb-bbbbbbbbbbbb';
const put = (progress, suffix = '', headers = {}) => fetch(path + suffix, { method: 'PUT', headers: { 'Content-Type': 'application/json', ...headers }, body: JSON.stringify(progress) });
assert.equal((await fetch(`${base}/health`)).status, 200);
const first = recordAnswer(emptyDocument(), a, '260', true, 1), second = recordAnswer(emptyDocument(), b, '28', false, 2);
const concurrent = await Promise.all([put(first), put(second)]);
assert.ok(concurrent.every(r => r.ok));
let saved = await (await fetch(path)).json();
assert.equal(summarize(saved.progress).totals.answered, 2);
await put(mergeDocuments(first, second)); await put(first);
saved = await (await fetch(path)).json();
assert.equal(summarize(saved.progress).totals.answered, 2);
assert.equal((await fetch(path)).headers.get('cache-control'), 'no-store');
assert.equal((await fetch(path, { headers: { Origin: 'https://abubakr380.github.io' } })).headers.get('access-control-allow-origin'), 'https://abubakr380.github.io');
assert.equal((await put(first, '', { Origin: 'https://unrelated.example' })).status, 403);
assert.equal((await fetch(path, { method: 'OPTIONS', headers: { Origin: 'https://abubakr380.github.io', 'Access-Control-Request-Method': 'PUT' } })).status, 204);
assert.equal((await put({ version: 9 })).status, 400);
assert.equal((await fetch(path, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: 'x'.repeat(262145) })).status, 413);
assert.equal((await fetch(`${base}/api/progress/ab`)).status, 400);
assert.equal((await fetch(`${base}/api/progress`)).status, 404);
assert.equal((await fetch(path, { method: 'DELETE' })).status, 405);
await put(emptyDocument(1)); await put(second);
saved = await (await fetch(path)).json();
assert.equal(summarize(saved.progress).totals.answered, 0);
console.log('D1 integration passed: concurrent merge, retries, reset, CORS, validation, payload limits, no cache, no listing.');
